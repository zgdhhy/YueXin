/**
 * 按模型 id 查参数：忽略大小写、vendor/ 前缀与 [1m] 之类的后缀；
 * 查不到时用最长的前缀匹配（如 deepseek-v4-flash-0731 → deepseek-v4-flash）。
 */
export function lookupModel(modelId: string): CatalogModel | undefined {
  const id = modelId.toLowerCase().split("/").pop()!.replace(/\[.*\]$/, "");
  const exact = MAP.get(id);
  if (exact) return exact;
  let best: string | undefined;
  for (const key of MAP.keys()) {
    if (id.startsWith(`${key}-`) && (!best || key.length > best.length)) best = key;
  }
  return best ? MAP.get(best) : undefined;
}
